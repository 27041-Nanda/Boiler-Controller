namespace AppLogger;

/// <summary>
/// Specifies the severity level of a log entry.
/// </summary>
public enum LogLevel
{
    /// <summary>
    /// Informational message.
    /// </summary>
    Info,

    /// <summary>
    /// Warning condition.
    /// </summary>
    Warning,

    /// <summary>
    /// Error condition.
    /// </summary>
    Error
}
